#!/usr/bin/env bash
set -euo pipefail

REPORT_AUTHOR="${REPORT_AUTHOR:-Миленькова Ивана}"
ROOT="reports/winter-2026-task4"
LOG_DIR="$ROOT/logs"
IMG_DIR="$ROOT/images"
INPUT="$ROOT/apache_logs"
OUTPUT="$ROOT/cleaned.log"
URL='https://raw.githubusercontent.com/elastic/examples/refs/heads/master/Common%20Data%20Formats/apache_logs/apache_logs'
mkdir -p "$LOG_DIR" "$IMG_DIR"

curl --fail --location --silent --show-error "$URL" -o "$INPUT"
{
  echo '$ curl ... -o apache_logs'
  echo '$ sed -E "s/192.../[LOCAL]/g; /404/d; date conversion expressions" apache_logs > cleaned.log'
  sed -E \
    -e 's/192\.168\.[0-9]+\.[0-9]+/[LOCAL]/g' \
    -e '/404/d' \
    -e 's#\[([0-9]{2})/Jan/([0-9]{4}):([0-9]{2}):([0-9]{2}):([0-9]{2}) ([+-][0-9]{4})\]#\1 Jan \2 \3:\4:\5#' \
    -e 's#\[([0-9]{2})/Feb/([0-9]{4}):([0-9]{2}):([0-9]{2}):([0-9]{2}) ([+-][0-9]{4})\]#\1 Feb \2 \3:\4:\5#' \
    -e 's#\[([0-9]{2})/Mar/([0-9]{4}):([0-9]{2}):([0-9]{2}):([0-9]{2}) ([+-][0-9]{4})\]#\1 Mar \2 \3:\4:\5#' \
    -e 's#\[([0-9]{2})/Apr/([0-9]{4}):([0-9]{2}):([0-9]{2}):([0-9]{2}) ([+-][0-9]{4})\]#\1 Apr \2 \3:\4:\5#' \
    -e 's#\[([0-9]{2})/May/([0-9]{4}):([0-9]{2}):([0-9]{2}):([0-9]{2}) ([+-][0-9]{4})\]#\1 May \2 \3:\4:\5#' \
    -e 's#\[([0-9]{2})/Jun/([0-9]{4}):([0-9]{2}):([0-9]{2}):([0-9]{2}) ([+-][0-9]{4})\]#\1 Jun \2 \3:\4:\5#' \
    -e 's#\[([0-9]{2})/Jul/([0-9]{4}):([0-9]{2}):([0-9]{2}):([0-9]{2}) ([+-][0-9]{4})\]#\1 Jul \2 \3:\4:\5#' \
    -e 's#\[([0-9]{2})/Aug/([0-9]{4}):([0-9]{2}):([0-9]{2}):([0-9]{2}) ([+-][0-9]{4})\]#\1 Aug \2 \3:\4:\5#' \
    -e 's#\[([0-9]{2})/Sep/([0-9]{4}):([0-9]{2}):([0-9]{2}):([0-9]{2}) ([+-][0-9]{4})\]#\1 Sep \2 \3:\4:\5#' \
    -e 's#\[([0-9]{2})/Oct/([0-9]{4}):([0-9]{2}):([0-9]{2}):([0-9]{2}) ([+-][0-9]{4})\]#\1 Oct \2 \3:\4:\5#' \
    -e 's#\[([0-9]{2})/Nov/([0-9]{4}):([0-9]{2}):([0-9]{2}):([0-9]{2}) ([+-][0-9]{4})\]#\1 Nov \2 \3:\4:\5#' \
    -e 's#\[([0-9]{2})/Dec/([0-9]{4}):([0-9]{2}):([0-9]{2}):([0-9]{2}) ([+-][0-9]{4})\]#\1 Dec \2 \3:\4:\5#' \
    -e 's#([0-9]{2}) Jan ([0-9]{4}) ([0-9]{2}:[0-9]{2}:[0-9]{2})#\2-01-\1 \3#' \
    -e 's#([0-9]{2}) Feb ([0-9]{4}) ([0-9]{2}:[0-9]{2}:[0-9]{2})#\2-02-\1 \3#' \
    -e 's#([0-9]{2}) Mar ([0-9]{4}) ([0-9]{2}:[0-9]{2}:[0-9]{2})#\2-03-\1 \3#' \
    -e 's#([0-9]{2}) Apr ([0-9]{4}) ([0-9]{2}:[0-9]{2}:[0-9]{2})#\2-04-\1 \3#' \
    -e 's#([0-9]{2}) May ([0-9]{4}) ([0-9]{2}:[0-9]{2}:[0-9]{2})#\2-05-\1 \3#' \
    -e 's#([0-9]{2}) Jun ([0-9]{4}) ([0-9]{2}:[0-9]{2}:[0-9]{2})#\2-06-\1 \3#' \
    -e 's#([0-9]{2}) Jul ([0-9]{4}) ([0-9]{2}:[0-9]{2}:[0-9]{2})#\2-07-\1 \3#' \
    -e 's#([0-9]{2}) Aug ([0-9]{4}) ([0-9]{2}:[0-9]{2}:[0-9]{2})#\2-08-\1 \3#' \
    -e 's#([0-9]{2}) Sep ([0-9]{4}) ([0-9]{2}:[0-9]{2}:[0-9]{2})#\2-09-\1 \3#' \
    -e 's#([0-9]{2}) Oct ([0-9]{4}) ([0-9]{2}:[0-9]{2}:[0-9]{2})#\2-10-\1 \3#' \
    -e 's#([0-9]{2}) Nov ([0-9]{4}) ([0-9]{2}:[0-9]{2}:[0-9]{2})#\2-11-\1 \3#' \
    -e 's#([0-9]{2}) Dec ([0-9]{4}) ([0-9]{2}:[0-9]{2}:[0-9]{2})#\2-12-\1 \3#' \
    "$INPUT" > "$OUTPUT"
  echo
  echo '--- input (first 3 lines) ---'; head -n 3 "$INPUT"
  echo '--- output (first 3 lines) ---'; head -n 3 "$OUTPUT"
} > "$LOG_DIR/01_sed.txt"
python3 scripts/text_to_png.py "$LOG_DIR/01_sed.txt" "$IMG_DIR/01_sed.png" --title "Команды sed и фрагменты"

python3 - "$ROOT/report.json" "$IMG_DIR/01_sed.png" "$REPORT_AUTHOR" <<'PY'
import json, sys
from pathlib import Path
manifest = {
  'title': 'Отчёт по практической работа номер 4 (зима 2026) ' + sys.argv[3],
  'subtitle': 'Очистка Apache-логов с помощью sed.',
  'metadata': [
    {'label': 'Источник', 'value': 'Elastic examples apache_logs'},
    {'label': 'Результат', 'value': 'reports/winter-2026-task4/cleaned.log'},
    {'label': 'Инструмент', 'value': 'sed -E'},
  ],
  'sections': [
    {'heading': '1. Загрузка и преобразования', 'body': [
      'Исходный файл скачан из raw.githubusercontent.com. Команда sed заменяет адреса 192.168.x.x на [LOCAL], удаляет строки, содержащие 404, и преобразует дату [DD/Mon/YYYY:HH:MM:SS +0000] в YYYY-MM-DD HH:MM:SS, сохраняя остальные поля строки.',
    ], 'image': sys.argv[2], 'caption': 'Команды и фрагменты входного и очищенного файла.'},
    {'heading': '2. Результат', 'body': [
      'Очищенный файл сохранён как cleaned.log. Удаление выполняется до форматирования даты; поэтому строки с 404 не попадают в результат.',
    ]},
  ],
}
Path(sys.argv[1]).write_text(json.dumps(manifest, ensure_ascii=False, indent=2), encoding='utf-8')
PY
python3 scripts/build_pdf_report.py "$ROOT/report.json" "$ROOT/report.pdf"
echo "Winter 2026 sed PDF report generated at $ROOT/report.pdf"
